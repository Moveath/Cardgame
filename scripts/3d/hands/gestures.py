def fingers_at(bend, target_fingers=None):
    """Четыре пальца на доле сжатия bend: 0 — расслабленная кисть, 1 — кулак (или target_fingers, если заданы)."""
    target = FIST["fingers"] if target_fingers is None else target_fingers
    planes = PLANES[:-1] + ((1., {name: values[3:] for name, values in target.items()}),)
    (b0, p0), (b1, p1) = next((a, b) for a, b in zip(planes, planes[1:]) if bend <= b[0] + 1e-9)
    share = (bend - b0) / (b1 - b0)
    fingers = {}
    for name, idle in IDLE["fingers"].items():
        fist = target[name]
        fingers[name] = lerp(idle[:3], fist[:3], bend) + lerp(p0[name], p1[name], share)
    return fingers


def half_closed(bend):
    """Пальцы на доле сжатия bend, большой палец отведён: для подбора плоскостей сгиба (gesture_fit.py, «Bend:0.3»)."""
    return dict(THUMB_READY, fingers=fingers_at(bend), cup=lerp(IDLE["cup"], FIST["cup"], bend), wrist=(0, 0))


def closing(frame):
    """Поза на кадре сжатия: 0 — расслабленная кисть, CLOSED — кулак."""
    bend = smooth(frame / FINGERS_CLOSED)
    fingers = fingers_at(bend)
    out = smooth(frame / THUMB_READY_AT)
    wrap = smooth((frame - THUMB_WRAP_FROM) / (CLOSED - THUMB_WRAP_FROM))
    thumb = {key: lerp(lerp(IDLE[key], THUMB_READY[key], out), FIST[key], wrap) for key in ("thumb", "thumb_turn", "thumb_bend")}
    # Сдвиг основания большого пальца есть только у кулака: входит вместе с тем, как палец ложится на пальцы.
    if "thumb_base" in FIST:
        thumb["thumb_base"] = lerp((0., 0., 0.), FIST["thumb_base"], wrap)
    return dict(thumb, fingers=fingers, cup=lerp(IDLE["cup"], FIST["cup"], bend), wrist=lerp(IDLE["wrist"], FIST["wrist"], bend))


def idle_fist_idle():
    """Клип: расслабленная кисть — кулак — расслабленная кисть. Разжимается кисть в обратном порядке: сначала уходит
    большой палец, потом раскрываются пальцы."""
    frames = [closing(f) for f in range(CLOSED + 1)]
    return frames + [frames[-1]] * HOLD + frames[::-1]


