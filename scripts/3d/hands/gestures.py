# Сжатие в кулак, кадры: пальцы закрываются за FINGERS_CLOSED кадров, большой палец к этому времени отведён
# (THUMB_READY_AT) и ложится на пальцы с кадра THUMB_WRAP_FROM по CLOSED.
FINGERS_CLOSED, THUMB_READY_AT, THUMB_WRAP_FROM, CLOSED, HOLD = 13, 9, 9, 18, 10


def smooth(x):
    x = min(1., max(0., x))
    return x * x * (3 - 2 * x)


def lerp(a, b, t):
    if isinstance(a, tuple):
        return tuple(lerp(p, q, t) for p, q in zip(a, b))
    return a + (b - a) * t


# Курс и наклон пальцев по пути от расслабленной кисти (0) к кулаку (1): (доля сжатия, {палец: (курс, наклон)}).
# Сгибы идут от одной позы к другой ровно, а плоскости сгиба — через эти промежуточные значения: они подобраны по коже
# (gesture_fit.py), чтобы полусогнутые пальцы не входили друг в друга. По прямой между позами средний и безымянный
# скрещивались на 3,9 мм, безымянный и мизинец — на 3,5 мм.
